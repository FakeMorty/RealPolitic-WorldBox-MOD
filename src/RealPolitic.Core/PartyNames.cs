/// Синхронизация со страной. Коренное имя державы (то, что мод хранит отдельно от титула:
/// «Ракрог», а не «Барство Ракрог») ставится в кавычках — «Народная партия «Ракрог»».
/// Почему в кавычках, а не «партия Ракрога»: склонять чужие имена по падежам — это
/// гарантированные «партия Ракрогии» и «партия Ыына». Кавычки читаются по-русски
/// правильно всегда и одинаково для любого имени.
///
/// Выбор названия постоянен: одно и то же государство всегда получает одну и ту же партию,
