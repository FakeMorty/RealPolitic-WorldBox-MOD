	/// <summary>Запасной набор, если идеологии вдруг нет в таблице.</summary>
	private static readonly string[] FallbackAdjectives =
	{
		"Народная", "Свободная", "Гражданская", "Общая", "Старая",
		"Вольная", "Родная", "Тихая", "Соборная", "Державная"
	};

	/// <summary>Все 50 названий идеологии без привязки к стране — для проверок и подсказок.</summary>
	public static IReadOnlyList<string> Variants(IdeologyType ideology)
	{
		string[] adjectives = Adjectives.TryGetValue(ideology, out string[] found) ? found : FallbackAdjectives;
		List<string> result = new List<string>(adjectives.Length * Forms.Length);
		for (int i = 0; i < adjectives.Length; i++)
		{
			for (int f = 0; f < Forms.Length; f++)
			{
				result.Add(adjectives[i] + " " + Forms[f]);
			}
		}
		return result;
	}

	/// <summary>
	/// Название партии для державы: постоянно для пары «держава + идеология».
	/// stateRoot — коренное имя державы («Ракрог»); если пусто, название будет без «портрета» страны.
	/// </summary>
	public static string For(IdeologyType ideology, string stateRoot, int kingdomId)
	{
		IReadOnlyList<string> variants = Variants(ideology);
		if (variants.Count == 0)
		{
			return string.Empty;
		}
		// Устойчивый выбор: тот же номер державы и та же идеология — то же название.
		uint hash = (uint)kingdomId * 2654435761u ^ (uint)ideology * 7919u;
		int index = (int)(hash % (uint)variants.Count);
		string name = variants[index];
		name = char.ToUpperInvariant(name[0]) + name.Substring(1);
		if (string.IsNullOrWhiteSpace(stateRoot))
		{
			return name;
		}
		return name + " «" + stateRoot.Trim() + "»";
	}

	/// <summary>Короткое имя без страны — для мест, где строка и так узкая.</summary>
	public static string Short(IdeologyType ideology, int kingdomId, int ordinal)
	{
		IReadOnlyList<string> variants = Variants(ideology);
		if (variants.Count == 0)
		{
			return string.Empty;
		}
		uint hash = (uint)kingdomId * 2246822519u ^ (uint)ideology * 3266489917u ^ (uint)ordinal * 668265263u;
		string name = variants[(int)(hash % (uint)variants.Count)];
		return char.ToUpperInvariant(name[0]) + name.Substring(1);
	}
